@app.post("/api/profile/avatar")
@require_auth
def upload_avatar():
    user = current_user()
    file = request.files.get("avatar")
    if not file or not file.filename:
        return jsonify({"error": "Выбери изображение."}), 400
    raw = file.read(2 * 1024 * 1024 + 1)
    if len(raw) > 2 * 1024 * 1024:
        return jsonify({"error": "Размер изображения не должен превышать 2 МБ."}), 413
    signature = None
    ext = None
    if raw.startswith(b"\x89PNG\r\n\x1a\n"):
        signature, ext = "image/png", ".png"
    elif raw.startswith(b"\xff\xd8\xff"):
        signature, ext = "image/jpeg", ".jpg"
    elif len(raw) >= 12 and raw[:4] == b"RIFF" and raw[8:12] == b"WEBP":
        signature, ext = "image/webp", ".webp"
    if not signature:
        return jsonify({"error": "Поддерживаются только изображения PNG, JPEG и WebP."}), 400
    filename = secure_filename(user["id"]) + ext
    target = UPLOAD_DIR / filename
    # Remove an earlier avatar in another supported format.
    for other_ext in (".png", ".jpg", ".webp"):
        old = UPLOAD_DIR / (secure_filename(user["id"]) + other_ext)
        if old.exists() and old != target:
            old.unlink(missing_ok=True)
    target.write_bytes(raw)
    user["avatar"] = f"/static/uploads/{filename}?v={int(utcnow().timestamp())}"
    save_db()
    return jsonify({"user": public_user(user), "message": "Аватар обновлён."})


