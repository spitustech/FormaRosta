def award_xp(user_id: str, source_key: str, points: int, description: str) -> bool:
    unique = f"{user_id}:{source_key}"
    if any(e.get("unique_key") == unique for e in DB["xp_events"]):
        return False
    DB["xp_events"].append({"id": uid("xp_"), "user_id": user_id, "source_key": source_key, "unique_key": unique, "points": max(0, int(points)), "description": description, "created_at": iso_now()})
