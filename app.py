def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def iso_now() -> str:
    return utcnow().isoformat(timespec="seconds")


def uid(prefix: str = "") -> str:
    return f"{prefix}{uuid.uuid4().hex[:12]}"


def parse_date(value: str | None) -> date | None:
    if not value:
        return None
    try:
        return date.fromisoformat(str(value)[:10])
    except (ValueError, TypeError):
        return None


def valid_timezone(value: str | None) -> str:
    if value:
        try:
            ZoneInfo(value)
            return value
        except (ZoneInfoNotFoundError, ValueError):
            pass
    return "Europe/Moscow"


def today_for_user(user: dict) -> date:
    try:
        return utcnow().astimezone(ZoneInfo(valid_timezone(user.get("timezone")))).date()
    except Exception:
        return utcnow().date()


def blank_db() -> dict:
    return {"users": [], "exercises": [], "workouts": [], "xp_events": [], "mission_completions": [], "email_tokens": []}


def save_db() -> None:
    temp_path = DB_PATH.with_suffix(".tmp")
    with DB_LOCK:
        temp_path.write_text(json.dumps(DB, ensure_ascii=False, indent=2), encoding="utf-8")
        temp_path.replace(DB_PATH)


def load_db() -> dict:
    if DB_PATH.exists():
        try:
            loaded = json.loads(DB_PATH.read_text(encoding="utf-8"))
            for key, default in blank_db().items():
                loaded.setdefault(key, default)
            return loaded
        except (json.JSONDecodeError, OSError):
            backup = DB_PATH.with_name(f"database.corrupt-{int(utcnow().timestamp())}.json")
            try:
                DB_PATH.replace(backup)
            except OSError:
                pass
    return blank_db()


DB = load_db()


def level_info(total_xp: int) -> dict:
    total_xp = max(0, int(total_xp))
    level = 1
    floor_xp = 0
    requirement = 100
    while total_xp >= floor_xp + requirement:
        floor_xp += requirement
        level += 1
        requirement = 100 + (level - 1) * 50
    return {"level": level, "xp": total_xp, "current_level_xp": total_xp - floor_xp, "next_level_xp": requirement, "level_floor_xp": floor_xp, "next_level_at": floor_xp + requirement, "progress_percent": round((total_xp - floor_xp) / requirement * 100)}


