def period_bounds(user: dict, period: str, start_str: str | None = None, end_str: str | None = None) -> tuple[date | None, date]:
    today = today_for_user(user)
    if period == "week":
        start = today - timedelta(days=today.weekday())
        return start, start + timedelta(days=6)
    if period == "7d":
        return today - timedelta(days=6), today
    if period == "30d":
        return today - timedelta(days=29), today
    if period == "month":
        return today.replace(day=1), today
    if period == "year":
        return today.replace(month=1, day=1), today
    if period == "custom":
        start = parse_date(start_str) or today - timedelta(days=29)
        end = parse_date(end_str) or today
        if end < start:
            start, end = end, start
        return start, end
    if period == "all":
        return None, today
    return today - timedelta(days=29), today


@app.get("/api/stats")
@require_auth
def stats():
    user = current_user()
    period = request.args.get("period", "30d")
    start, end = period_bounds(user, period, request.args.get("start"), request.args.get("end"))
    all_workouts = user_workouts(user["id"])
    selected = [w for w in all_workouts if parse_date(w.get("date")) and (start is None or parse_date(w.get("date")) >= start) and parse_date(w.get("date")) <= end]
    selected.sort(key=lambda w: w.get("date", ""))
    total_minutes = sum(activity_minutes(w) for w in selected)
    volume = round(sum(workout_volume(w) for w in selected))
    unique_count = len(unique_exercises(selected))
    # Avoid a single mixed scale: each exercise record uses that exercise's own meaningful metric.
    grouped: dict[str, list[dict]] = defaultdict(list)
    for w in selected:
        for item in w.get("exercises", []):
            grouped[item.get("exercise_id", "unknown")].append({**item, "date": w.get("date"), "workout_title": w.get("title")})
    progression = []
    for ex_id, rows in grouped.items():
        ex = exercise_by_id(ex_id) or {"name": rows[0].get("name", "Упражнение"), "metric": "reps"}
        metric = ex.get("metric", "reps")
        vals = []
        for row in rows:
            value = exercise_metric(ex, row)
            if value > 0:
                vals.append({"date": row["date"], "value": value, "title": row["workout_title"]})
        if vals:
            progression.append({"exercise_id": ex_id, "name": ex.get("name", "Упражнение"), "muscle_group": ex.get("muscle_group", ""), "metric": metric, "unit": {"weight": "кг", "reps": "повторения", "duration": "мин", "distance": "км"}.get(metric, ""), "points": vals, "best": max(x["value"] for x in vals)})
    progression.sort(key=lambda x: x["name"])
    # Daily or monthly activity buckets based on period length.
    if period == "year":
        buckets = {}
        cursor = end.replace(month=1, day=1)
        while cursor <= end:
            key = cursor.strftime("%Y-%m")
            buckets[key] = {"date": key, "label": ["янв", "фев", "мар", "апр", "май", "июн", "июл", "авг", "сен", "окт", "ноя", "дек"][cursor.month - 1], "count": 0, "minutes": 0}
            if cursor.month == 12:
                cursor = cursor.replace(year=cursor.year + 1, month=1)
            else:
                cursor = cursor.replace(month=cursor.month + 1)
        for w in selected:
            key = (parse_date(w["date"]) or end).strftime("%Y-%m")
            if key in buckets:
                buckets[key]["count"] += 1
                buckets[key]["minutes"] += activity_minutes(w)
        activity = list(buckets.values())
    else:
        bucket_start = start or (min((parse_date(w["date"]) for w in selected if parse_date(w.get("date"))), default=end))
        if (end - bucket_start).days > 399:
            bucket_start = end - timedelta(days=399)
        span = min(400, max(1, (end - bucket_start).days + 1))
        buckets = { (bucket_start + timedelta(days=i)).isoformat(): {"date": (bucket_start + timedelta(days=i)).isoformat(), "label": f"{(bucket_start + timedelta(days=i)).day} { ['янв','фев','мар','апр','мая','июн','июл','авг','сен','окт','ноя','дек'][(bucket_start + timedelta(days=i)).month - 1] }", "count": 0, "minutes": 0} for i in range(span) }
        for w in selected:
            d = parse_date(w.get("date"))
            if d and d.isoformat() in buckets:
                buckets[d.isoformat()]["count"] += 1
                buckets[d.isoformat()]["minutes"] += activity_minutes(w)
        activity = list(buckets.values())
    # Record list includes lifetime personal bests, shown alongside selected period trends.
    lifetime_records: dict[str, dict] = {}
    for w in all_workouts:
        for item in w.get("exercises", []):
            ex_id = item.get("exercise_id")
            ex = exercise_by_id(ex_id) or {"name": item.get("name", "Упражнение"), "metric": "reps"}
            value = exercise_metric(ex, item)
            if value <= 0:
                continue
            prev = lifetime_records.get(ex_id)
            if not prev or value > prev["value"]:
                lifetime_records[ex_id] = {"exercise_id": ex_id, "name": ex.get("name", item.get("name", "Упражнение")), "metric": ex.get("metric", "reps"), "unit": {"weight": "кг", "reps": "повторения", "duration": "мин", "distance": "км"}.get(ex.get("metric", "reps"), ""), "value": value, "date": w.get("date")}
    records = sorted(lifetime_records.values(), key=lambda x: x["date"], reverse=True)
    effective_start = start or min((parse_date(w["date"]) for w in selected if parse_date(w.get("date"))), default=end)
    weeks_in_range = max(1, ((end - effective_start).days + 1) / 7)
    return jsonify({"period": period, "start": start.isoformat() if start else None, "end": end.isoformat(), "summary": {"workouts": len(selected), "minutes": total_minutes, "volume_kg": volume, "unique_exercises": unique_count, "average_per_week": round(len(selected) / weeks_in_range, 1)}, "activity": activity, "progression": progression, "records": records})


