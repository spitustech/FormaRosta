def require_auth(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        user = current_user()
        if not user:
            return jsonify({"error": "Для этого действия войдите в аккаунт."}), 401
        return fn(*args, **kwargs)
    return wrapper


