def user_workouts(user_id: str, completed_only: bool = True) -> list[dict]:
    return [w for w in DB["workouts"] if w.get("user_id") == user_id and (not completed_only or w.get("completed", True))]


def exercise_by_id(exercise_id: str | None) -> dict | None:
    return next((e for e in DB["exercises"] if e.get("id") == exercise_id), None)


def unique_exercises(workouts: list[dict]) -> set[str]:
    result = set()
    for workout in workouts:
        for item in workout.get("exercises", []):
            if item.get("exercise_id"):
                result.add(item["exercise_id"])
    return result


def exercise_metric(exercise: dict, item: dict) -> float:
    metric = (exercise or {}).get("metric", "reps")
    fields = {"weight": "weight_kg", "reps": "reps", "duration": "duration_min", "distance": "distance_km"}
    try:
        return float(item.get(fields.get(metric, "reps"), 0) or 0)
    except (ValueError, TypeError):
        return 0.0


def workout_records(workouts: list[dict]) -> dict[str, float]:
    records: dict[str, float] = {}
    for workout in workouts:
        for item in workout.get("exercises", []):
            ex_id = item.get("exercise_id")
            ex = exercise_by_id(ex_id) or {"metric": "reps"}
            value = exercise_metric(ex, item)
            if value > records.get(ex_id, 0):
                records[ex_id] = value
    return records


def streak_info(user: dict) -> dict:
    dates = sorted({parse_date(w.get("date")) for w in user_workouts(user["id"]) if parse_date(w.get("date")) is not None})
    if not dates:
        return {"current": 0, "best": 0, "last_date": None, "active_today": False}
    best = 1
    run = 1
    for i in range(1, len(dates)):
        if (dates[i] - dates[i - 1]).days == 1:
            run += 1
        else:
            run = 1
        best = max(best, run)
    today = today_for_user(user)
    last = dates[-1]
    active = last == today
    if last < today - timedelta(days=1):
        current = 0
    else:
        current = 1
        cursor = last
        for day in reversed(dates[:-1]):
            if (cursor - day).days == 1:
                current += 1
                cursor = day
            elif (cursor - day).days > 1:
                break
    return {"current": current, "best": best, "last_date": last.isoformat(), "active_today": active}


def current_week_bounds(user: dict) -> tuple[date, date, str]:
    today = today_for_user(user)
    start = today - timedelta(days=today.weekday())
    end = start + timedelta(days=6)
    return start, end, f"{start.isocalendar().year}-W{start.isocalendar().week:02d}"


def mission_progress(user: dict, mission: dict) -> int:
    workouts = user_workouts(user["id"])
    week_start, week_end, _ = current_week_bounds(user)
    this_week = [w for w in workouts if parse_date(w.get("date")) and week_start <= parse_date(w.get("date")) <= week_end]
    kind = mission["kind"]
    if kind == "weekly_workouts":
        return len(this_week)
    if kind == "weekly_exercises":
        return len(unique_exercises(this_week))
    if kind == "weekly_record":
        before = [w for w in workouts if parse_date(w.get("date")) and parse_date(w.get("date")) < week_start]
        prior_records = workout_records(before)
        for workout in this_week:
            for item in workout.get("exercises", []):
                ex_id = item.get("exercise_id")
                ex = exercise_by_id(ex_id) or {"metric": "reps"}
                value = exercise_metric(ex, item)
                if value > prior_records.get(ex_id, 0):
                    return 1
        return 0
    return 0


