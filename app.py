@app.post("/api/profile/change-email")
@require_auth
def change_email():
    user = current_user()
    if user.get("is_demo"):
        return jsonify({"error": "В демонстрационном профиле нельзя менять адрес электронной почты."}), 403
    data = request.get_json(silent=True) or {}
    email = str(data.get("email", "")).strip().lower()
    if len(email) > 254 or not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", email):
        return jsonify({"error": "Введи корректный новый адрес электронной почты."}), 400
    if email == user.get("email", "").lower():
        return jsonify({"error": "Это уже ваш текущий адрес."}), 400
    if any(u.get("email", "").lower() == email for u in DB["users"]):
        return jsonify({"error": "Этот адрес уже используется."}), 409
    token = secrets.token_urlsafe(18)
    expires = (utcnow() + timedelta(hours=1)).isoformat(timespec="seconds")
    user["email_pending"] = {"email": email, "token_hash": generate_password_hash(token), "expires_at": expires}
    DB["email_tokens"] = [t for t in DB["email_tokens"] if t.get("user_id") != user["id"]]
    DB["email_tokens"].append({"user_id": user["id"], "email": email, "token_hash": user["email_pending"]["token_hash"], "expires_at": expires})
    save_db()
    # Local development returns a verification code instead of pretending an email was sent.
    response = {"message": "Запрос на смену адреса создан. В демонстрационном режиме используйте код ниже.", "email": email, "development_code": token if os.environ.get("APP_ENV", "development") != "production" else None}
    return jsonify(response), 202


@app.post("/api/profile/confirm-email")
@require_auth
def confirm_email():
    user = current_user()
    data = request.get_json(silent=True) or {}
    token = str(data.get("code", ""))
    pending = user.get("email_pending")
    if not pending or not token or not check_password_hash(pending.get("token_hash", ""), token):
        return jsonify({"error": "Код подтверждения неверен или устарел."}), 400
    try:
        expires = datetime.fromisoformat(pending["expires_at"])
        if expires.tzinfo is None:
            expires = expires.replace(tzinfo=timezone.utc)
    except (ValueError, KeyError):
        expires = utcnow() - timedelta(seconds=1)
    if utcnow() > expires:
        user["email_pending"] = None
        save_db()
        return jsonify({"error": "Срок действия кода истёк. Запросите смену адреса снова."}), 400
    new_email = pending["email"]
    if any(u["id"] != user["id"] and u.get("email", "").lower() == new_email.lower() for u in DB["users"]):
        return jsonify({"error": "Этот адрес уже используется другим аккаунтом."}), 409
    user["email"] = new_email
    user["email_pending"] = None
    DB["email_tokens"] = [t for t in DB["email_tokens"] if t.get("user_id") != user["id"]]
    save_db()
    return jsonify({"user": public_user(user), "message": "Адрес электронной почты подтверждён и изменён."})


